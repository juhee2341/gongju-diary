/** "{N}자까지" 같은 자리표시자 치환 */
export function fill(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{([^{}]+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

